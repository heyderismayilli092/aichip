import os
import time
import json
# LangChain imports
from langchain_community.vectorstores import Chroma
from langchain_community.llms import LlamaCpp
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.runnables import RunnablePassthrough, RunnableLambda
from langchain_community.embeddings import HuggingFaceEmbeddings

# -------------------- SETTINGS --------------------
with open("config.json", "r") as configfile:
  data = json.load(configfile)
embedding_model = data["embed-model"]  # HuggingFace embedding model
rag_folder = data["rag-folder"]  # RAG database directory
MAX_TOKENS = data["max-tokens"]  # The maximum number of tokens for the answer generated by LLM


def ask(promptdata, question, ragdir, llm, top_k):
    now = time.time()
    ragdir = rag_folder+"/"+ragdir
    if not os.path.exists(ragdir):
      return "Database folder not found !"
    # -------------------- START-UP: EMBEDDING VE DB --------------------
    print("Loading RAG vector database...")
    embedding = HuggingFaceEmbeddings(model_name=embedding_model)
    vectordb = Chroma(persist_directory=ragdir, embedding_function=embedding)
    retriever = vectordb.as_retriever(search_kwargs={"k": top_k})
    
    # -------------------- RAG PROMPT --------------------
    prompt = ChatPromptTemplate.from_template("""
{prompt_data}

Question: {question}

Context:
{context}
""")

    # -------------------- RAG CHAIN --------------------
    rag_chain = (
        {
          "context": retriever,
          "question": RunnablePassthrough(),
          "prompt_data": RunnableLambda(lambda _: promptdata),
        }
        | prompt
        | llm
    )
    print("Vector DB loaded.")

    # --- RETRIEVAL ---
    try:
        retrieved_docs = retriever.invoke(question)
    except Exception as e:
        return jsonify({"error": f"retriever failed: {e}"}), 500

    # --- RAG LLM ANSWER ---
    try:
        result = rag_chain.invoke(question, max_tokens=MAX_TOKENS)
        answer_text = str(result)
    except Exception as e:
        return jsonify({"error": f"LLM failed: {e}"}), 500

    # --- GATHER THE RESOURCES ---
    sources = []
    for d in retrieved_docs:
        meta = getattr(d, "metadata", None)
        if meta and "source" in meta:
            src = meta["source"]
        else:
            src = getattr(d, "source", None) or getattr(d, "page_content", "")[:80]
        if src and src not in sources:
            sources.append(src)
    return {"answer": answer_text, "sources": sources, "cached": False}



def askai_stream(promptdata, question, ragdir, llm, top_k):
    now = time.time()
    ragdir = rag_folder+"/"+ragdir
    if not os.path.exists(ragdir):
        return "Database folder not found !"

    # -------------------- START-UP: EMBEDDING VE DB --------------------
    print("Loading RAG vector database...")
    embedding = HuggingFaceEmbeddings(model_name=embedding_model)
    # Chroma database
    vectordb = Chroma(
        persist_directory=ragdir,
        embedding_function=embedding
    )
    # Retriever
    retriever = vectordb.as_retriever(
        search_kwargs={"k": top_k}
    )
    print("Vector DB loaded.")

    # -------------------- RAG PROMPT --------------------
    prompt = ChatPromptTemplate.from_template("""
{prompt_data}

Question: {question}

Context:
{context}
    """)

    # -------------------- RAG CHAIN --------------------
    rag_chain = (
        {
            "context": retriever,
            "question": RunnablePassthrough(),
            "prompt_data": RunnableLambda(lambda _: promptdata),
        }
        | prompt
        | llm  # NOTE: It MUST be an LLM that supports streaming
    )

    # -------------------- STREAMING GENERATOR --------------------
    # The LLM generates the response in chunks and sends it to the frontend instantly

    # ---- GET THE RESOURCES FIRST ----
    try:
        retrieved_docs = retriever.invoke(question)
    except Exception as e:
        yield f"\n[ERROR] retriever failed: {e}\n"
        return

    sources = []
    for d in retrieved_docs:
       meta = getattr(d, "metadata", None)
       if meta and "source" in meta:
          src = meta["source"]
       else:
          src = getattr(d, "source", None) or d.page_content[:80]
       if src and src not in sources:
           sources.append(src)

    # ---- LLM STREAM LOAD ----
    try:
        for chunk in rag_chain.stream(question):
            yield chunk
    except Exception as e:
        yield f"\n[ERROR] LLM failed: {e}\n"
        return

    # ---- Sources Send ----
    yield "\n\n---\n"
    yield "Sources:\n"
    for s in sources:
        yield f"- {s}\n"

